import math
from typing import Callable, List, Optional, Protocol, Sequence, Union


# Documented sentinel value for undefined cosine similarity (zero vector)
UNDEFINED_SENTINEL: float = float("nan")


def cosine_similarity(v1: Sequence[float], v2: Sequence[float]) -> float:
    """
    Computes cosine similarity between two numeric vectors:
      similarity = (v1 . v2) / (||v1|| * ||v2||)

    Zero vector policy:
      If either vector has norm 0 (or all zeros), the cosine similarity
      is undefined and returns the documented sentinel: float('nan').
    """
    if len(v1) != len(v2):
        raise ValueError(f"Vector dimension mismatch: {len(v1)} vs {len(v2)}")
    if len(v1) == 0:
        raise ValueError("Cannot compute similarity on empty vectors.")

    dot_product = sum(a * b for a, b in zip(v1, v2))
    norm_v1 = math.sqrt(sum(a * a for a in v1))
    norm_v2 = math.sqrt(sum(b * b for b in v2))

    # Explicit zero norm handling
    if norm_v1 == 0.0 or norm_v2 == 0.0:
        return UNDEFINED_SENTINEL

    val = dot_product / (norm_v1 * norm_v2)
    # Clamp small numerical float imprecisions to [-1.0, 1.0]
    return max(-1.0, min(1.0, val))


