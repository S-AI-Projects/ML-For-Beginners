# Service Interface & Offline Adapter
# ---------------------------------------------------------------------------

class EmbeddingService(Protocol):
    """Callable interface definition for embedding vector lookup."""
    def __call__(self, text: str) -> List[float]:
        ...


class LocalOfflineEmbeddingAdapter:
    """
    Deterministic offline adapter satisfying the EmbeddingService callable interface.
    Supplies fixed embedding fixtures without network, GPU, or external API requirements.

    Real-service behavior this mock does NOT establish:
    1. Remote network transport (TCP/TLS handshake, connection pooling, retries).
    2. API authentication, token expiration, or header authorization.
    3. Live service latency, queuing, timeouts, or jitter.
    4. Production rate limits, concurrency bounds, or HTTP 429 backoff.
    5. Continuous high-dimensional semantic vector spaces generated by deep neural nets.
    """

    def __init__(self, vocabulary_embeddings: Optional[dict] = None):
        if vocabulary_embeddings is None:
            # Standard 2D local fixtures
            self._vocab = {
                "base": [1.0, 0.0],
                "same": [1.0, 0.0],
                "orthogonal": [0.0, 1.0],
                "opposite": [-1.0, 0.0],
                "empty_zero": [0.0, 0.0],
            }
        else:
            self._vocab = dict(vocabulary_embeddings)

    def __call__(self, text: str) -> List[float]:
        """Lookup embedding vector for text key, default to [0.0, 0.0] if unknown."""
        key = text.lower().strip()
        if key in self._vocab:
            return list(self._vocab[key])
        return [0.0, 0.0]


def compare_texts_via_adapter(
    adapter: EmbeddingService,
    text1: str,
    text2: str
) -> float:
    """Uses the callable adapter to embed two texts and compare via cosine similarity."""
    v1 = adapter(text1)
    v2 = adapter(text2)
    return cosine_similarity(v1, v2)


def run_demo():
    print("=== Cosine-Similarity Lookup Demo ===")
    v_base = [1.0, 0.0]
    v_same = [1.0, 0.0]
    v_orth = [0.0, 1.0]
    v_zero = [0.0, 0.0]

    sim_same = cosine_similarity(v_base, v_same)
    sim_orth = cosine_similarity(v_base, v_orth)
    sim_zero = cosine_similarity(v_base, v_zero)

    print(f"[1, 0] vs [1, 0] (same)       : {sim_same} (Expected: 1.0)")
    print(f"[1, 0] vs [0, 1] (orthogonal) : {sim_orth} (Expected: 0.0)")
    print(f"[1, 0] vs [0, 0] (zero vector): {sim_zero} (math.isnan: {math.isnan(sim_zero)})")

    adapter = LocalOfflineEmbeddingAdapter()
    adapter_sim = compare_texts_via_adapter(adapter, "base", "same")
    print(f"Via adapter ('base' vs 'same'): {adapter_sim}")


if __name__ == "__main__":
    run_demo()
